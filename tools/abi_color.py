"""Validate and emit the allocation-free packed sRGB color contract."""


def _require(ok, message):
    if not ok:
        raise ValueError(message)


def _integer(value, low, high):
    _require(type(value) is int and low <= value <= high,
             'color integer outside bounds')


def validate_color(schema):
    """The optional closed descriptor applies to every host color argument."""
    _require(type(schema) is dict, 'color schema must be an object')
    if 'color_value' not in schema:
        return
    _integer(schema.get('minor'), 1, 65535)
    descriptor = schema['color_value']
    _require(type(descriptor) is dict and set(descriptor) ==
             set('since type color_space channels reserved_mask alpha invalid_status'.split()),
             'color descriptor keys')
    _integer(descriptor['since'], 1, schema['minor'])
    _require(descriptor['type'] == 'u32', 'color scalar type')
    _require(descriptor['color_space'] == 'srgb', 'color space')
    _require(descriptor['alpha'] == 'none', 'color has no alpha')
    _require(descriptor['invalid_status'] == 'ERR_INVALID', 'color invalid status')
    _integer(descriptor['reserved_mask'], 0xff000000, 0xff000000)
    channels = descriptor['channels']
    _require(type(channels) is list and len(channels) == 3, 'color channels')
    for item, name, shift in zip(channels, ('red', 'green', 'blue'), (16, 8, 0)):
        _require(type(item) is dict and set(item) == {'name', 'shift', 'bits'} and
                 item['name'] == name, 'color channel shape')
        _integer(item['shift'], shift, shift)
        _integer(item['bits'], 8, 8)
    statuses = schema.get('statuses')
    _require(type(statuses) is list, 'color needs statuses')
    entries = [item for item in statuses if type(item) is dict and
               item.get('name') == descriptor['invalid_status']]
    _require(len(entries) == 1 and type(entries[0].get('value')) is int and
             entries[0]['value'] == -2, 'color status contract')
    _integer(entries[0].get('since'), 1, descriptor['since'])
    hosts = schema.get('host_entries')
    _require(type(hosts) is list, 'color needs host entries')
    for entry in hosts:
        _require(type(entry) is dict and type(entry.get('args')) is list,
                 'color host shape')
        for arg in entry['args']:
            _require(type(arg) is dict, 'color argument shape')
            if arg.get('name') == 'color':
                _require(arg.get('type') == descriptor['type'] and
                         entry.get('result') == 'status', 'color argument contract')


def compatible_color(old, new, minimum_since):
    """Published encodings are immutable; first addition respects the floor."""
    validate_color(old)
    validate_color(new)
    _integer(minimum_since, 1, 65536)
    before, after = old.get('color_value'), new.get('color_value')
    if before is None:
        if after is not None:
            _require(after['since'] >= minimum_since, 'backdated color value')
        return
    _require(after == before, 'changed or removed color value contract')


def rust_color(schema):
    """Emit an independent no_std numeric codec, or nothing for old schemas."""
    validate_color(schema)
    if 'color_value' not in schema:
        return ''
    descriptor = schema['color_value']
    replacements = {'@MASK@': f"0x{descriptor['reserved_mask']:08x}"}
    encoded, decoded = [], []
    for item, argument in zip(descriptor['channels'], ('r', 'g', 'b')):
        shift = item['shift']
        encoded.append(f'(({argument} as u32) << {shift})' if shift else f'{argument} as u32')
        decoded.append(f'(value >> {shift}) as u8' if shift else 'value as u8')
    replacements['@ENCODE@'] = ' | '.join(encoded)
    replacements['@DECODE@'] = ', '.join(decoded)
    replacements['@INVALID@'] = str(next(item['value'] for item in schema['statuses']
                                       if item['name'] == descriptor['invalid_status']))
    source = '''// Generated by tools/abi-gen.py; do not edit.
/// Encode three 8-bit sRGB channels as the numeric value `0x00RRGGBB`.
/// There is no alpha channel. This function never allocates.
pub const fn color_encode(r: u8, g: u8, b: u8) -> u32 {
    @ENCODE@
}

/// Decode a numeric `0x00RRGGBB` value into red, green and blue channels.
/// Nonzero reserved high bits return ERR_INVALID before drawing.
pub const fn color_decode(value: u32) -> Result<[u8; 3], i32> {
    if value & @MASK@ != 0 {
        return Err(@INVALID@);
    }
    Ok([@DECODE@])
}
'''
    for marker, value in replacements.items():
        source = source.replace(marker, value)
    return source
