"""Validate and emit the bounded, allocation-free settings value wire codec."""


def _require(ok, message):
    if not ok:
        raise ValueError(message)


def _keys(value, names):
    _require(type(value) is dict and set(value) == set(names.split()),
             'settings value keys: ' + names)


def _integer(value, low, high):
    _require(type(value) is int and low <= value <= high,
             'settings value integer outside bounds')


def validate_settings(schema):
    """The descriptor is optional, closed, and independent of host slot types."""
    _require(type(schema) is dict, 'settings schema must be an object')
    if 'settings_value' not in schema:
        return
    _integer(schema.get('minor'), 1, 65535)
    descriptor = schema['settings_value']
    _keys(descriptor, 'since layout byte_order max_bytes header kinds')
    _integer(descriptor['since'], 1, schema['minor'])
    _integer(descriptor['layout'], 1, 1)
    _require(descriptor['byte_order'] == 'little', 'unsupported settings byte order')
    _integer(descriptor['max_bytes'], 12, 4096)
    header = descriptor['header']
    _require(type(header) is list and len(header) == 3, 'settings header fields')
    for field, name in zip(header, ('layout', 'kind', 'payload_bytes')):
        _keys(field, 'name type')
        _require(field == dict(name=name, type='u32'), 'settings header fields')
    kinds = descriptor['kinds']
    _require(type(kinds) is list and len(kinds) == 4, 'settings value kinds')
    for item, name, tag, wire, cap in zip(
            kinds, ('absent', 'bool', 'int', 'text'), range(4),
            ('none', 'bool', 'i64', 'utf8'), (0, 1, 8, descriptor['max_bytes'] - 12)):
        _keys(item, 'name tag type max_bytes')
        _require(item['name'] == name and item['type'] == wire, 'settings value kinds')
        _integer(item['tag'], tag, tag)
        _integer(item['max_bytes'], cap, cap)
    _require(descriptor['max_bytes'] >= 20, 'settings cap must fit every scalar')
    statuses = schema.get('statuses')
    _require(type(statuses) is list, 'settings value needs statuses')
    for name, value in [('ERR_UNSUPPORTED', -1), ('ERR_INVALID', -2),
                        ('ERR_NO_SPACE', -3), ('ERR_UTF8', -5)]:
        entries = [item for item in statuses if type(item) is dict and item.get('name') == name]
        _require(len(entries) == 1 and type(entries[0].get('value')) is int and
                 entries[0]['value'] == value, 'settings value status contract')
        _integer(entries[0].get('since'), 1, descriptor['since'])


def compatible_settings(old, new, minimum_since):
    """A published layout cannot change; adding it respects the release floor."""
    validate_settings(old)
    validate_settings(new)
    _integer(minimum_since, 1, 65536)
    before, after = old.get('settings_value'), new.get('settings_value')
    if before is None:
        if after is not None:
            _require(after['since'] >= minimum_since, 'backdated settings value')
        return
    _require(after is not None, 'removed settings value')
    _require(before == after, 'changed settings value contract')


def rust_settings(schema):
    """Emit a self-contained no_std codec, or nothing for an older schema."""
    validate_settings(schema)
    if 'settings_value' not in schema:
        return ''
    descriptor = schema['settings_value']
    kinds = {item['name']: item for item in descriptor['kinds']}
    offsets = {field['name']: index * 4 for index, field in enumerate(descriptor['header'])}
    header_bytes = len(descriptor['header']) * 4
    errors = {item['name']: item['value'] for item in schema['statuses']}
    replacements = {
        '@LAYOUT@': descriptor['layout'], '@HEADER@': header_bytes,
        '@MAX@': descriptor['max_bytes'], '@TEXT_MAX@': kinds['text']['max_bytes'],
        '@LAYOUT_OFFSET@': offsets['layout'], '@KIND_OFFSET@': offsets['kind'],
        '@PAYLOAD_OFFSET@': offsets['payload_bytes'],
        '@LAYOUT_END@': offsets['layout'] + 4, '@KIND_END@': offsets['kind'] + 4,
        '@PAYLOAD_END@': offsets['payload_bytes'] + 4,
        '@ABSENT@': kinds['absent']['tag'], '@BOOL@': kinds['bool']['tag'],
        '@INT@': kinds['int']['tag'], '@TEXT@': kinds['text']['tag'],
        '@BOOL_BYTES@': kinds['bool']['max_bytes'], '@INT_BYTES@': kinds['int']['max_bytes'],
        '@UNSUPPORTED@': errors['ERR_UNSUPPORTED'], '@INVALID@': errors['ERR_INVALID'],
        '@NO_SPACE@': errors['ERR_NO_SPACE'], '@UTF8@': errors['ERR_UTF8'],
    }
    source = '''// Generated by tools/abi-gen.py; do not edit.
/// Settings value wire layout revision.
pub const SETTINGS_LAYOUT: u32 = @LAYOUT@;
/// Fixed wire header length in bytes.
pub const SETTINGS_HEADER_BYTES: usize = @HEADER@;
/// Maximum complete wire value length in bytes.
pub const SETTINGS_MAX_BYTES: usize = @MAX@;
/// Maximum UTF-8 text payload length in bytes.
pub const SETTINGS_MAX_TEXT_BYTES: usize = @TEXT_MAX@;

/// A settings value borrowed for this call. No Rust value crosses the ABI.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum SettingValueRef<'a> {
    /// The setting has no value.
    Absent,
    /// A Boolean value.
    Bool(bool),
    /// A signed integer value.
    Int(i64),
    /// Borrowed UTF-8 text.
    Text(&'a str),
}

/// Encode a canonical value, returning its full required length.
///
/// Only the prefix fitting in `out` is written. An oversized value returns
/// ERR_NO_SPACE before writing any bytes. This function never allocates.
pub fn settings_encode(
    value: SettingValueRef<'_>,
    out: &mut [core::mem::MaybeUninit<u8>],
) -> Result<usize, i32> {
    let integer;
    let boolean;
    let (kind, payload): (u32, &[u8]) = match value {
        SettingValueRef::Absent => (@ABSENT@, &[]),
        SettingValueRef::Bool(value) => {
            boolean = [u8::from(value)];
            (@BOOL@, &boolean)
        }
        SettingValueRef::Int(value) => {
            integer = value.to_le_bytes();
            (@INT@, &integer)
        }
        SettingValueRef::Text(value) => {
            if value.len() > SETTINGS_MAX_TEXT_BYTES {
                return Err(@NO_SPACE@);
            }
            (@TEXT@, value.as_bytes())
        }
    };
    let required = SETTINGS_HEADER_BYTES + payload.len();
    let mut header = [0_u8; SETTINGS_HEADER_BYTES];
    header[@LAYOUT_OFFSET@..@LAYOUT_END@].copy_from_slice(&SETTINGS_LAYOUT.to_le_bytes());
    header[@KIND_OFFSET@..@KIND_END@].copy_from_slice(&kind.to_le_bytes());
    header[@PAYLOAD_OFFSET@..@PAYLOAD_END@].copy_from_slice(&(payload.len() as u32).to_le_bytes());
    for (slot, byte) in out.iter_mut().zip(header.iter().chain(payload)) {
        slot.write(*byte);
    }
    Ok(required)
}

/// Decode one complete canonical value without allocating.
///
/// Unknown layouts or kinds return ERR_UNSUPPORTED. Invalid framing or scalar
/// payloads return ERR_INVALID. Invalid text returns ERR_UTF8.
pub fn settings_decode(bytes: &[u8]) -> Result<SettingValueRef<'_>, i32> {
    if bytes.len() < SETTINGS_HEADER_BYTES {
        return Err(@INVALID@);
    }
    let read = |offset: usize| {
        u32::from_le_bytes([
            bytes[offset],
            bytes[offset + 1],
            bytes[offset + 2],
            bytes[offset + 3],
        ])
    };
    if read(@LAYOUT_OFFSET@) != SETTINGS_LAYOUT {
        return Err(@UNSUPPORTED@);
    }
    let kind = read(@KIND_OFFSET@);
    if ![@ABSENT@, @BOOL@, @INT@, @TEXT@].contains(&kind) {
        return Err(@UNSUPPORTED@);
    }
    let payload = &bytes[SETTINGS_HEADER_BYTES..];
    if bytes.len() > SETTINGS_MAX_BYTES || read(@PAYLOAD_OFFSET@) as usize != payload.len() {
        return Err(@INVALID@);
    }
    match kind {
        @ABSENT@ if payload.is_empty() => Ok(SettingValueRef::Absent),
        @BOOL@ if payload.len() == @BOOL_BYTES@ => match payload[0] {
            0 => Ok(SettingValueRef::Bool(false)),
            1 => Ok(SettingValueRef::Bool(true)),
            _ => Err(@INVALID@),
        },
        @INT@ if payload.len() == @INT_BYTES@ => Ok(SettingValueRef::Int(i64::from_le_bytes([
            payload[0], payload[1], payload[2], payload[3], payload[4], payload[5], payload[6],
            payload[7],
        ]))),
        @TEXT@ if payload.len() <= SETTINGS_MAX_TEXT_BYTES => core::str::from_utf8(payload)
            .map(SettingValueRef::Text)
            .map_err(|_| @UTF8@),
        _ => Err(@INVALID@),
    }
}
'''
    for marker, value in replacements.items():
        source = source.replace(marker, str(value))
    return source
