#!/usr/bin/env python3
"""Generate shells/xteink/src/proto_table.rs: a plain [usize; N] of the addresses of the public,
non-generic functions the plugins share with the firmware (cat.json). EXPERIMENT ONLY."""
import json,re,sys,collections,subprocess
repo='/workspaces/paperpaw/firmware-engineer/paperpaw'
cat=json.load(open('/home/agent/fw-jobs/proto/cat.json'))
drop=set(json.load(open('/home/agent/fw-jobs/proto/drop.json'))) if len(sys.argv)>2 and sys.argv[2]=='prune' else set()
# api paths
api=collections.defaultdict(list)   # (crate, ty, name) -> [path]
for f in subprocess.run(['bash','-c',f'ls {repo}/crates/*/api.txt'],capture_output=True,text=True).stdout.split():
    for line in open(f):
        m=re.match(r'^pub (?:unsafe |const |async )*fn (paperpaw_\w+)::([^(]*)\(',line)
        if not m: continue
        crate=m[1]; path=m[1]+'::'+m[2]
        path=re.sub(r"<'[^>]*>","",path)        # lifetimes only
        path=re.sub(r"<[^>]*>$","",path)        # generics on the method itself
        segs=path.split('::')
        if '<' in path or '>' in path: continue  # real type generics: skip
        ty=segs[-2] if len(segs)>=3 else None
        api[(crate,ty,segs[-1])].append(path)
entries=[]   # (expr, name, size)
for d,r in cat['matched']:
    m=re.match(r'^<(.+?)(?: as (.+))?>::(\w+)$',d)
    exprs=[]
    if m:
        ty=m[1]; tr=m[2]; meth=m[3]
        tyn=re.sub(r'<.*$','',ty).split('::')[-1]; crate=ty.split('::')[0]
        paths=api.get((crate,tyn,meth),[])
        for p in paths:
            tp='::'.join(p.split('::')[:-1])
            exprs.append(f'<{tp} as {tr}>::{meth}' if tr else p)
    else:
        segs=d.split('::'); crate=segs[0]; name=segs[-1]; mod=segs[-2] if len(segs)>=3 else None
        cands=[p for (c,t,n),ps in api.items() if c==crate and n==name for p in ps if '::'.join(p.split('::')[:-1]) and True]
        cands=[p for p in cands if len(p.split('::'))>=2]
        # free fn: the module path of the api entry must end in the module of the symbol or equal
        good=[p for p in cands if (len(p.split('::'))>=3 and p.split('::')[-2]==mod) or True]
        exprs=sorted(set(good))
        # a method of a type whose name was taken for a module (type None) is not a free fn
        exprs=[p for p in exprs if p.split('::')[-2][0].islower() or len(p.split('::'))==2]
    for e in exprs:
        entries.append((e,d,r['size']))
seen=set(); out=[]
for e,d,s in entries:
    if e in seen or e in drop: continue
    seen.add(e); out.append((e,d,s))
json.dump(out,open('/home/agent/fw-jobs/proto/table_entries.json','w'))
def arr(name,sel):
    lines=[f'pub static {name}: Table<{len(sel)}> = Table([']
    for e,d,s in sel: lines.append(f'    {e} as *const (), // {s} B')
    lines.append(']);')
    return '\n'.join(lines)
big=[x for x in out if x[2]>=256]
src='''//! EXPERIMENT ONLY (branch proto/shared-table, #44): the addresses of the public, non-generic
//! functions code plugins share with the firmware, as a plain table. Generated by
//! ~/fw-jobs/proto/gen_table.py; never to be merged.
#![allow(clippy::all, unused)]

/// A plain array of function addresses.
pub struct Table<const N: usize>(pub [*const (); N]);
// SAFETY: addresses of functions, never written.
unsafe impl<const N: usize> Sync for Table<N> {}

'''+f'#[cfg(feature = "proto-all")]\n'+arr('TABLE',out)+'\n\n#[cfg(all(feature = "proto-big", not(feature = "proto-all")))]\n'+arr('TABLE',big)+'''

/// Keeps the table in the image: reads one entry chosen at run time.
pub fn touch(n: u64) -> usize {
    let table = core::hint::black_box(&TABLE.0);
    // SAFETY: the index is within the table.
    unsafe { core::ptr::read_volatile(table.as_ptr().add((n as usize) % table.len())) as usize }
}
'''
open(repo+'/shells/xteink/src/proto_table.rs','w').write(src)
print(len(out),'entries,',len(big),'big')
