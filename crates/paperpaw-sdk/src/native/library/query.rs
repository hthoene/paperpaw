use super::*;

/// Which books a library query includes.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub enum Show {
    /// Every book.
    #[default]
    All,
    /// Books not opened yet.
    Unread,
    /// Books being read.
    Reading,
    /// Finished books.
    Finished,
    /// Favourites.
    Favourites,
    /// Books added recently and not opened.
    New,
}
/// Catalog ordering.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub enum Sort {
    /// By title.
    #[default]
    Title,
    /// By author.
    Author,
    /// By series and number.
    Series,
    /// By added day.
    Added,
    /// By last opening.
    RecentlyOpened,
}
/// A catalog page position; continue only with the cursor returned by a page.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CatalogCursor {
    pub(super) offset: u32,
    pub(super) generation: u32,
}
impl CatalogCursor {
    /// Start a fresh query.
    #[must_use]
    pub const fn start() -> Self {
        Self {
            offset: 0,
            generation: 0,
        }
    }
}
/// Borrowed, lossless catalog filters. Overlong text is refused before the host call.
#[derive(Clone, Copy, Debug)]
pub struct Query<'a> {
    row: wire::ServiceLibQuery<'a>,
    pub(super) cursor: CatalogCursor,
}
impl Default for Query<'_> {
    fn default() -> Self {
        Self::new()
    }
}
impl<'a> Query<'a> {
    /// All books, ordered by title, from the first page.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            row: wire::ServiceLibQuery {
                show: 0,
                sort: 0,
                flags: 0,
                words: "",
                author: "",
                series: "",
                tag: "",
                folder: "",
                added_since: 0,
                cursor: 0,
                generation: 0,
                facet: 0,
            },
            cursor: CatalogCursor::start(),
        }
    }
    /// Filter by reading status.
    #[must_use]
    pub fn show(mut self, show: Show) -> Self {
        self.row.show = match show {
            Show::All => 0,
            Show::Unread => 1,
            Show::Reading => 2,
            Show::Finished => 3,
            Show::Favourites => 4,
            Show::New => 5,
        };
        self
    }
    /// Choose catalog ordering.
    #[must_use]
    pub fn sort(mut self, sort: Sort) -> Self {
        self.row.sort = match sort {
            Sort::Title => 0,
            Sort::Author => 1,
            Sort::Series => 2,
            Sort::Added => 3,
            Sort::RecentlyOpened => 4,
        };
        self
    }
    /// Reverse the ordering.
    #[must_use]
    pub const fn descending(mut self, enabled: bool) -> Self {
        self.row.flags = (self.row.flags & !1) | enabled as u32;
        self
    }
    /// Leave out the archive folder.
    #[must_use]
    pub const fn exclude_archive(mut self, enabled: bool) -> Self {
        self.row.flags = (self.row.flags & !2) | ((enabled as u32) << 1);
        self
    }
    /// Include books added on or after this day since 1970.
    #[must_use]
    pub const fn added_since(mut self, day: u32) -> Self {
        self.row.added_since = day;
        self
    }
    /// Continue the same filters from a previous page.
    #[must_use]
    pub const fn cursor(mut self, cursor: CatalogCursor) -> Self {
        self.cursor = cursor;
        self
    }
    pub(super) fn record(self) -> Record<'a> {
        let mut row = self.row;
        row.cursor = self.cursor.offset;
        row.generation = self.cursor.generation;
        Record::ServiceLibQuery(row)
    }
}
macro_rules! filter {
    ($name:ident, $cap:ident, $doc:literal) => {
        impl<'a> Query<'a> {
            #[doc=$doc]
            ///
            /// # Errors
            /// NoSpace above the generated byte cap; the text is never shortened.
            pub fn $name(mut self, value: &'a str) -> Result<Self, Error> {
                if value.len() > wire::$cap {
                    return Err(Error::NoSpace);
                }
                self.row.$name = value;
                Ok(self)
            }
        }
    };
}
filter!(
    words,
    SERVICE_LIB_QUERY_WORDS_MAX_BYTES,
    "Search title, author, series, tags and filename."
);
filter!(
    author,
    SERVICE_LIB_QUERY_AUTHOR_MAX_BYTES,
    "Filter by author."
);
filter!(
    series,
    SERVICE_LIB_QUERY_SERIES_MAX_BYTES,
    "Filter by series."
);
filter!(tag, SERVICE_LIB_QUERY_TAG_MAX_BYTES, "Filter by tag.");
filter!(
    folder,
    SERVICE_LIB_QUERY_FOLDER_MAX_BYTES,
    "Filter to this folder and descendants."
);
