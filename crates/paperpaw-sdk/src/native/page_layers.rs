/// The text stage's key, as `registration.stage` and `Event::StageCall` name it.
pub const TEXT_STAGE: &str = text::KEY;
/// The layer stage's key.
pub const LAYER_STAGE: &str = layer::KEY;
/// The most bytes of a block's text a [`TextAsk::Block`] carries (a longer
/// block's text is cut there, at a character).
pub const MAX_BLOCK_TEXT: usize = text::TEXT_BLOCK_TEXT_MAX_BYTES;
/// The most bytes of the text one [`TextAnswer::replace`] puts in.
pub const MAX_REPLACEMENT: usize = text::TEXT_REPLACE_WITH_MAX_BYTES;
/// The most bytes of one gloss's text (a sentence's translation).
pub const MAX_GLOSS: usize = text::TEXT_GLOSS_TEXT_MAX_BYTES;
/// The most bytes of one [`LayerAnswer::text`].
pub const MAX_LAYER_TEXT: usize = layer::LAYER_TEXT_TEXT_MAX_BYTES;
/// The most bytes of the text of one inserted block.
pub const MAX_INSERTED: usize = text::TEXT_INSERT_TEXT_MAX_BYTES;
/// The most room above or below a line, in hundredths of an em (four ems).
pub const MAX_ROOM: u16 = 400;
/// The most records one answer holds.
pub const MAX_ROWS: usize = text::REPLY_ROWS;
/// The most bytes of one answer: the reply buffer a subscriber is lent.
pub const MAX_ANSWER: usize = text::MAX_REPLY;

fn invalid(_: i32) -> Error {
    Error::Invalid
}

fn status(code: i32) -> Error {
    match code {
        -3 => Error::NoSpace,
        _ => Error::Invalid,
    }
}

/// What a block of the book is (`text.block.kind`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum BlockKind {
    /// A paragraph of text.
    Paragraph,
    /// A heading.
    Heading,
    /// Another block of text: a list's item, a quote, a table's row.
    Other,
}

/// A block of the book, as the reader is about to lay it out.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct TextBlock<'a> {
    /// The section (chapter) it is in.
    pub section: u32,
    /// Where it starts in the section's source: with `section`, a place in
    /// the book that stays while the book does.
    pub offset: u32,
    /// What it is.
    pub kind: BlockKind,
    /// Its text as the layout sets it (whitespace collapsed), at most
    /// [`MAX_BLOCK_TEXT`] bytes of it. The ranges of an answer are byte
    /// ranges of this text.
    pub text: &'a str,
}

/// What the reader asks of the text stage.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum TextAsk<'a> {
    /// A book opened (or a setting changed): whether the plugin adds to it.
    /// Answer [`TextAnswer::uses`] with a signature other than 0 to be shown
    /// its blocks; answer nothing to leave the book alone.
    Book {
        /// The book's path in the library.
        path: &'a str,
        /// Its language (a BCP 47 tag), empty where unknown.
        language: &'a str,
    },
    /// A block before its layout.
    Block(TextBlock<'a>),
}

impl<'a> TextAsk<'a> {
    /// Reads the ask from the payload of the stage call.
    ///
    /// # Errors
    /// `Invalid` for a payload that is not one ask of the text stage.
    pub fn decode(payload: &'a [u8]) -> Result<Self, Error> {
        let mut rows = text::input_decode(payload).map_err(invalid)?;
        match rows.next() {
            Some(Ok(text::Record::TextBook(book))) => Ok(Self::Book {
                path: book.path,
                language: book.language,
            }),
            Some(Ok(text::Record::TextBlock(block))) => Ok(Self::Block(TextBlock {
                section: block.section,
                offset: block.offset,
                kind: match block.kind {
                    0 => BlockKind::Paragraph,
                    1 => BlockKind::Heading,
                    _ => BlockKind::Other,
                },
                text: block.text,
            })),
            _ => Err(Error::Invalid),
        }
    }
}

/// What a gloss is (`text.gloss.kind`): where it goes and how it is set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum GlossKind {
    /// How characters are read (furigana, pinyin): above the line, upright.
    Ruby,
    /// How a word sounds: above the line, upright.
    Phonetic,
    /// What it means (an interlinear gloss, a translation): below the line,
    /// in italics.
    Gloss,
}

impl GlossKind {
    const fn code(self) -> u32 {
        match self {
            Self::Ruby => 0,
            Self::Phonetic => 1,
            Self::Gloss => 2,
        }
    }
}

/// The answer to a [`TextAsk`], written into the reply buffer. A refused
/// record leaves the ones before it.
#[derive(Debug)]
pub struct TextAnswer<'w> {
    writer: text::ReplyWriter<'w>,
}

impl<'w> TextAnswer<'w> {
    /// An answer of no records yet, over `out` (`Reply::write_with`'s bytes).
    ///
    /// # Errors
    /// `NoSpace` for an empty `out`.
    pub fn new(out: &'w mut [u8]) -> Result<Self, Error> {
        text::ReplyWriter::new(out)
            .map(|writer| Self { writer })
            .map_err(status)
    }

    fn push(&mut self, record: &text::Record<'_>) -> Result<(), Error> {
        self.writer.push(record).map_err(status)
    }

    /// For [`TextAsk::Book`]: the plugin adds to this book; `signature` (not
    /// 0) changes whenever what it adds does.
    ///
    /// # Errors
    /// `Invalid` past [`MAX_ROWS`], `NoSpace` past the buffer.
    pub fn uses(&mut self, signature: u64) -> Result<(), Error> {
        self.push(&text::Record::TextUses(text::TextUses::new(signature)))
    }

    /// Room above and below each line of the block, in hundredths of an em
    /// of its text (at most [`MAX_ROOM`] each, more is cut). Room for its
    /// glosses is made without asking; this is for what a [`LayerAnswer`]
    /// draws there.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn room(&mut self, above: u16, below: u16) -> Result<(), Error> {
        let row = text::TextRoom::new(u32::from(above), u32::from(below));
        self.push(&text::Record::TextRoom(row))
    }

    /// Puts `with` in place of `range` of the block's text, as shown (the
    /// book's places stay: positions, highlights). Ranges of one answer must
    /// not overlap and must fall on characters; one that does not is left out.
    ///
    /// # Errors
    /// As [`uses`](Self::uses); `Invalid` for `with` over [`MAX_REPLACEMENT`].
    pub fn replace(&mut self, range: Range<u32>, with: &str) -> Result<(), Error> {
        let row = text::TextReplace::new(range.start, range.end, with);
        self.push(&text::Record::TextReplace(row))
    }

    /// Sets `text` over (ruby, phonetics) or under (a gloss) `range` of the
    /// block's text, at the start of the range, `size` in percent of the
    /// text (20 to 100; 0 for half). A gloss that would run into the one
    /// before it on the line moves on behind it; what passes the line's end
    /// is cut. Ranges refer to the text as asked, before any replacement; a
    /// gloss on a replaced part is left out.
    ///
    /// # Errors
    /// As [`uses`](Self::uses); `Invalid` for `text` over [`MAX_GLOSS`].
    pub fn gloss(
        &mut self,
        range: Range<u32>,
        kind: GlossKind,
        size: u16,
        text: &str,
    ) -> Result<(), Error> {
        let row = text::TextGloss::new(range.start, range.end, kind.code(), u32::from(size), text);
        self.push(&text::Record::TextGloss(row))
    }

    /// Inserts a block of `text` after this one (a translation of the
    /// paragraph, a note), `size` in percent of the text (0 for the same),
    /// in italics or not. It is shown but is not the book's: it has no place
    /// of its own, nothing on it is chosen or read aloud. At most four after
    /// a block, 4 KiB of text in all; keep it shorter than a page.
    ///
    /// # Errors
    /// As [`uses`](Self::uses); `Invalid` for `text` over [`MAX_INSERTED`].
    pub fn insert(&mut self, text: &str, size: u16, italic: bool) -> Result<(), Error> {
        let row = text::TextInsert::new(text, u32::from(size), u32::from(italic));
        self.push(&text::Record::TextInsert(row))
    }

    /// The bytes the answer took, for `Reply::write_with`.
    ///
    /// # Errors
    /// `Invalid` where the writer is broken.
    pub fn finish(self) -> Result<usize, Error> {
        self.writer.finish().map_err(status)
    }
}

/// A line of a laid-out page ([`LayerPage::lines`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct LayerLine<'a> {
    /// Its left edge.
    pub x: i32,
    /// Its baseline.
    pub baseline: i32,
    /// How wide its words are, from `x`.
    pub width: u32,
    /// The height of its words' boxes (its text's line), in pixels.
    pub size: u32,
    /// The room above its letters ([`TextAnswer::room`], ruby), in pixels:
    /// part of the line, above [`top`](Self::top).
    pub leading: u32,
    /// The top of its words' boxes. The room below a line (glosses,
    /// [`TextAnswer::room`]) reaches to the next line's `top - leading`.
    pub top: i32,
    /// The section it is in, and where its first word starts in the
    /// section's source (0 for an inserted line).
    pub section: u32,
    pub offset: u32,
    /// A line of a block a plugin inserted: not the book's.
    pub inserted: bool,
    /// Its text.
    pub text: &'a str,
    words: &'a [u8],
}

/// A word of a [`LayerLine`]: where it is drawn and where it is in the
/// line's text. A word whose place the reader does not know is 0 wide at 0
/// (it keeps its number in the line).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct LayerWord {
    /// Its left edge and width.
    pub x: u16,
    pub width: u16,
    /// The byte its text starts at in [`LayerLine::text`].
    pub at: u16,
}

/// The bytes of one packed [`LayerWord`] (`layer.line.words`): `x`, `width`
/// and `at`, each u16 little-endian.
pub const WORD_BYTES: usize = 6;

impl<'a> LayerLine<'a> {
    /// Its words, in the order of the text (the reader's word boxes); none
    /// for an inserted line.
    pub fn words(&self) -> impl Iterator<Item = LayerWord> + 'a {
        let (words, _) = self.words.as_chunks::<WORD_BYTES>();
        words.iter().map(|w| LayerWord {
            x: u16::from_le_bytes([w[0], w[1]]),
            width: u16::from_le_bytes([w[2], w[3]]),
            at: u16::from_le_bytes([w[4], w[5]]),
        })
    }
}

/// A laid-out page, or a part of it (a page of many lines is shown in more
/// than one ask, each with the lines from [`first`](Self::first) on).
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct LayerPage<'a> {
    /// The text area's size.
    pub width: u32,
    pub height: u32,
    /// The page's lines in all, and the number of the first in this ask.
    pub lines: u32,
    pub first: u32,
    /// The words being read aloud, for a plugin that follows reading aloud
    /// ([`LayerAnswer::uses_reading_aloud`]); none otherwise.
    pub spoken: Option<Spoken>,
    rows: layer::RecordStream<'a>,
}

/// The words of a page being read aloud: from word [`word`](Self::word) of
/// line [`line`](Self::line) (lines counted on the page, as
/// [`LayerPage::first`] counts them; words as [`LayerLine::words`] counts
/// them) up to, not including, word `end_word` of line `end_line`. The same
/// words in every ask of the page.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct Spoken {
    pub line: u32,
    pub word: u32,
    pub end_line: u32,
    pub end_word: u32,
}

impl Spoken {
    /// Whether word `word` of line `line` is one of them.
    #[must_use]
    pub fn holds(&self, line: u32, word: u32) -> bool {
        (line, word) >= (self.line, self.word) && (line, word) < (self.end_line, self.end_word)
    }
}

impl<'a> LayerPage<'a> {
    /// The lines of this ask, top to bottom.
    pub fn lines(&self) -> impl Iterator<Item = LayerLine<'a>> + 'a {
        self.rows.clone().filter_map(|row| match row {
            Ok(layer::Record::LayerLine(line)) => Some(LayerLine {
                x: line.x,
                baseline: line.baseline,
                width: line.width,
                size: line.size,
                leading: line.leading,
                top: line.top,
                section: line.section,
                offset: line.offset,
                inserted: line.inserted != 0,
                text: line.text,
                words: line.words,
            }),
            _ => None,
        })
    }
}

/// What the reader asks of the layer stage.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub enum LayerAsk<'a> {
    /// A book opened (or a setting changed): whether the plugin draws on its
    /// pages ([`LayerAnswer::uses`]).
    Book {
        /// The book's path in the library.
        path: &'a str,
        /// Its language, empty where unknown.
        language: &'a str,
    },
    /// A page, once after its layout.
    Page(LayerPage<'a>),
    /// A tap in the text area, for a plugin that asked for taps
    /// ([`LayerAnswer::input`]).
    Tap(LayerTap),
    /// A key action while the book is on show, for a plugin that asked for
    /// keys ([`LayerAnswer::input`]).
    Key(LayerKey<'a>),
}

/// A tap on the page on show (nothing chosen), for [`LayerAsk::Tap`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct LayerTap {
    /// Where, in pixels from the text area's top left (as the lines are).
    pub x: i32,
    pub y: i32,
    /// On the book's region (or anywhere on the text area without one).
    pub on_book: bool,
    /// Where the page on show starts in the book (its first line's place).
    pub section: u32,
    pub offset: u32,
}

/// A key action on the page on show (nothing chosen), for [`LayerAsk::Key`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct LayerKey<'a> {
    /// The action (`core.next`, `core.previous`, `core.confirm`, …).
    pub action: &'a str,
    /// Where the page on show starts in the book.
    pub section: u32,
    pub offset: u32,
}

/// Which taps in the text area a layer's plugin is shown first
/// ([`LayerAnswer::input`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum LayerTaps {
    /// None: they are the reader's.
    None,
    /// Those off the book's region ([`LayerAnswer::region`]): the plugin's part.
    OffBook,
    /// All of them, on the book's text too.
    All,
}

impl<'a> LayerAsk<'a> {
    /// Reads the ask from the payload of the stage call.
    ///
    /// # Errors
    /// `Invalid` for a payload that is not one ask of the layer stage.
    pub fn decode(payload: &'a [u8]) -> Result<Self, Error> {
        let mut rows = layer::input_decode(payload).map_err(invalid)?;
        match rows.next() {
            Some(Ok(layer::Record::LayerBook(book))) => Ok(Self::Book {
                path: book.path,
                language: book.language,
            }),
            Some(Ok(layer::Record::LayerPage(page))) => {
                let spoken = match rows.clone().next() {
                    Some(Ok(layer::Record::LayerTap(t))) => {
                        return Ok(Self::Tap(LayerTap {
                            x: t.x,
                            y: t.y,
                            on_book: t.book != 0,
                            section: t.section,
                            offset: t.offset,
                        }));
                    }
                    Some(Ok(layer::Record::LayerKey(k))) => {
                        return Ok(Self::Key(LayerKey {
                            action: k.action,
                            section: k.section,
                            offset: k.offset,
                        }));
                    }
                    Some(Ok(layer::Record::LayerAloud(a))) => Some(Spoken {
                        line: a.line,
                        word: a.word,
                        end_line: a.end_line,
                        end_word: a.end_word,
                    }),
                    _ => None,
                };
                Ok(Self::Page(LayerPage {
                    width: page.width,
                    height: page.height,
                    lines: page.lines,
                    first: page.first,
                    spoken,
                    rows,
                }))
            }
            _ => Err(Error::Invalid),
        }
    }
}

/// A gray of what a layer draws: 0 black to 255 white, or none.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Tone(u32);

impl Tone {
    /// Black.
    pub const BLACK: Tone = Tone(0);
    /// Nothing: no fill, no frame.
    pub const NONE: Tone = Tone(256);

    /// The gray `value` (0 black to 255 white).
    #[must_use]
    pub const fn gray(value: u8) -> Tone {
        Tone(value as u32)
    }
}

/// The answer to a [`LayerAsk`], written into the reply buffer.
#[derive(Debug)]
pub struct LayerAnswer<'w> {
    writer: layer::ReplyWriter<'w>,
}

impl<'w> LayerAnswer<'w> {
    /// An answer of no records yet, over `out`.
    ///
    /// # Errors
    /// `NoSpace` for an empty `out`.
    pub fn new(out: &'w mut [u8]) -> Result<Self, Error> {
        layer::ReplyWriter::new(out)
            .map(|writer| Self { writer })
            .map_err(status)
    }

    fn push(&mut self, record: &layer::Record<'_>) -> Result<(), Error> {
        self.writer.push(record).map_err(status)
    }

    /// For [`LayerAsk::Book`]: the plugin draws on this book's pages;
    /// `signature` (not 0) changes whenever what it draws does.
    ///
    /// # Errors
    /// `Invalid` past [`MAX_ROWS`], `NoSpace` past the buffer.
    pub fn uses(&mut self, signature: u64) -> Result<(), Error> {
        self.push(&layer::Record::LayerUses(layer::LayerUses::new(
            signature, 0,
        )))
    }

    /// [`uses`](Self::uses), and the plugin follows reading aloud: while the
    /// book is read aloud, the page on show is asked again for each sentence,
    /// with the words being read ([`LayerPage::spoken`]); what it answers is
    /// drawn in place of the answer before.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn uses_reading_aloud(&mut self, signature: u64) -> Result<(), Error> {
        self.push(&layer::Record::LayerUses(layer::LayerUses::new(
            signature, 1,
        )))
    }

    /// For [`LayerAsk::Book`], right after [`uses`](Self::uses): the reader
    /// sets the book's text only in this part of its text area, in
    /// thousandths of it (`x`, `y`, `width`, `height`, each side at least
    /// 100): the rest of the area is the layer's to draw on (the other half
    /// of a split page, a margin for notes). Positions in [`LayerAsk::Page`]
    /// stay those of the whole text area. A region outside the area or
    /// smaller is not used. Changing it lays the pages out anew.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn region(&mut self, (x, y): (u16, u16), (width, height): (u16, u16)) -> Result<(), Error> {
        let region = layer::LayerRegion::new(
            u32::from(x),
            u32::from(y),
            u32::from(width),
            u32::from(height),
        );
        self.push(&layer::Record::LayerRegion(region))
    }

    /// For [`LayerAsk::Book`], right after [`uses`](Self::uses) (before or
    /// after [`region`](Self::region)): the plugin is shown `taps` in the
    /// text area ([`LayerAsk::Tap`]) and, with `keys`, every key action while
    /// the book is on show ([`LayerAsk::Key`]) before the reader acts on
    /// them; what it does not take ([`taken`](Self::taken)) stays the
    /// reader's. Keys cost a call for each key press: ask for them only where
    /// the plugin needs them.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn input(&mut self, taps: LayerTaps, keys: bool) -> Result<(), Error> {
        let taps = match taps {
            LayerTaps::None => 0,
            LayerTaps::OffBook => 1,
            LayerTaps::All => 2,
        };
        let row = layer::LayerInput::new(taps, u32::from(keys));
        self.push(&layer::Record::LayerInput(row))
    }

    /// For [`LayerAsk::Tap`] and [`LayerAsk::Key`]: the plugin takes it (the
    /// reader does nothing with it). With `redraw`, the boxes, lines and text
    /// of this answer stand for the page's layer from now on, and the page is
    /// drawn again; without, the layer stays as it was.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn taken(&mut self, redraw: bool) -> Result<(), Error> {
        let row = layer::LayerTaken::new(u32::from(redraw));
        self.push(&layer::Record::LayerTaken(row))
    }

    /// A box at `(x, y)`, `width` by `height`, filled with `fill` and framed
    /// `thickness` pixels wide in `ink`.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn rect(
        &mut self,
        (x, y): (i32, i32),
        (width, height): (u32, u32),
        (fill, ink): (Tone, Tone),
        thickness: u32,
    ) -> Result<(), Error> {
        let row = layer::LayerBox::new(x, y, width, height, fill.0, ink.0, thickness);
        self.push(&layer::Record::LayerBox(row))
    }

    /// A line from `from` to `to`, `thickness` pixels wide in `ink`.
    ///
    /// # Errors
    /// As [`uses`](Self::uses).
    pub fn segment(
        &mut self,
        from: (i32, i32),
        to: (i32, i32),
        ink: Tone,
        thickness: u32,
    ) -> Result<(), Error> {
        let row = layer::LayerSegment::new(from.0, from.1, to.0, to.1, ink.0, thickness);
        self.push(&layer::Record::LayerSegment(row))
    }

    /// `text` in the reading font, its pen starting at `x` on the baseline
    /// `y`, `size` pixels high, in `ink`, in italics or not.
    ///
    /// # Errors
    /// As [`uses`](Self::uses); `Invalid` for `text` over [`MAX_LAYER_TEXT`].
    pub fn text(
        &mut self,
        (x, y): (i32, i32),
        (size, ink, italic): (u32, Tone, bool),
        text: &str,
    ) -> Result<(), Error> {
        let row = layer::LayerText::new(x, y, size, ink.0, u32::from(italic), text);
        self.push(&layer::Record::LayerText(row))
    }

    /// The bytes the answer took, for `Reply::write_with`.
    ///
    /// # Errors
    /// `Invalid` where the writer is broken.
    pub fn finish(self) -> Result<usize, Error> {
        self.writer.finish().map_err(status)
    }
}

