//! Page layers: what a plugin adds to the reader's pages (ADR 0032,
//! `docs/abi/page-layers.md`). The reader owns two stages a plugin subscribes
//! to with `registration.stage` (`Declarations::subscribe`):
//!
//! - **The text stage** [`TEXT_STAGE`] (`reader.text@1`): the reader asks once
//!   for each book ([`TextAsk::Book`]); a plugin that answers
//!   [`TextAnswer::uses`] with a signature other than 0 is then shown the text
//!   of each block before it is laid out ([`TextAsk::Block`]) and may ask for
//!   room above and below its lines, replace parts of its text, set glosses,
//!   ruby or phonetics over or under its words (the layout places them and the
//!   reader draws them), and insert small blocks after it. Each block is asked
//!   once while the book is open: page turns ask nothing.
//! - **The layer stage** [`LAYER_STAGE`] (`reader.layer@1`): asked once for each
//!   book the same way ([`LayerAsk::Book`]); the plugin that uses it is then
//!   shown each laid-out page once, its lines and the places of their words
//!   ([`LayerAsk::Page`]), and answers what it draws over the text: boxes,
//!   lines and text ([`LayerAnswer`]). The reader keeps the answer with the
//!   page and draws it whenever the page is drawn. A plugin may follow
//!   reading aloud ([`LayerAnswer::uses_reading_aloud`], [`LayerPage::spoken`])
//!   and give the book's text a part of the page only
//!   ([`LayerAnswer::region`]), drawing in the rest (a split page), and be
//!   shown taps and key actions first ([`LayerAnswer::input`],
//!   [`LayerAsk::Tap`], [`LayerAsk::Key`], [`LayerAnswer::taken`]).
//!
//! Without a subscriber nothing changes and nothing is kept. One plugin uses
//! each stage at a time: the first in stage order whose book answer says so.
//! A signature is part of the layout's key: answer another one when what the
//! plugin adds changes (its settings), and the pages are laid out anew. The
//! plugin is asked again for each book when a setting changes.
//!
//! In the plugin's `event`, for `Event::StageCall { stage, payload, .. }`
//! with `stage` one of the two: read the ask with [`TextAsk::decode`] or
//! [`LayerAsk::decode`] and write the answer into the reply with
//! `Reply::write_with` and [`TextAnswer`] or [`LayerAnswer`]. Positions are
//! pixels from the top left of the page's text area.
use super::Error;
use core::ops::Range;

