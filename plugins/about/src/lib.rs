//! *About PaperPaw*, in the device's settings: a page as the other
//! settings pages. Its rows are the version, the address of the source,
//! the plugins built into the firmware, the interface and draft code
//! plugins must be built for, and the licences.
//!
//! The page is the interface-7 plugin [`native_plugin::NativeAbout`]; the
//! interface-6 page is gone. Two rows wait on the host and say so: the
//! licences and the plugins built in open their text in the reader, which
//! needs `doc_open.root` 5 (draft 22, `command.open` into `core.reader`).
//! Other plugins' lines come through the plugin-defined stage `about.lines`
//! (`stages/about.lines@1.def`, codec `src/stages.rs` by
//! `tools/stage-codec.py`): a plugin subscribes (`registration.stage`) and
//! answers each run with one line; they are listed after the licences. The licences text
//! (`data/licences-*.md`, `tools/licences/build.py`) and the logo stay in
//! the crate for that slice.

#![no_std]

extern crate alloc;

/// Where PaperPaw's source is.
pub const SOURCE: &str = "https://github.com/hthoene/paperpaw";

#[path = "../declarations.rs"]
#[allow(
    dead_code,
    reason = "the build script and the declaration test also use the builders"
)]
mod declarations;
mod native_entry;
mod native_model;
#[allow(
    clippy::all,
    clippy::pedantic,
    reason = "generated by tools/stage-codec.py"
)]
mod stages;
#[cfg(feature = "linked")]
pub use native_entry::NATIVE_ENTRY;
/// The interface-7 plugin.
pub mod native_plugin;

/// The settings the plugin declares, made by its build script from the same
/// declarations as tables.
#[cfg(feature = "linked")]
mod native_settings {
    use paperpaw_sdk::SettingSpec;
    include!(concat!(env!("OUT_DIR"), "/about_settings.rs"));
}

/// The settings the plugin declares as a table kept in the program (as Beta 3
/// kept them), for a linked build to use in place of a copy on the heap of
/// each (`Kernel::register_linked`). Only a linked plugin has it.
#[cfg(feature = "linked")]
pub static NATIVE_SETTINGS: &[paperpaw_sdk::SettingSpec] = &native_settings::SETTINGS;

/// The setting groups the plugin declares, as a table kept in the program
/// like [`NATIVE_SETTINGS`].
#[cfg(feature = "linked")]
pub static NATIVE_GROUPS: &[paperpaw_sdk::SettingGroupSpec] = &native_settings::GROUPS;

/// The ids the plugin's declarations name, as a table kept in the program
/// like [`NATIVE_SETTINGS`].
#[cfg(feature = "linked")]
pub static NATIVE_IDS: &[paperpaw_sdk::Id] = &native_settings::IDS;

/// The id and title of each screen and action the plugin declares, as a table
/// kept in the program like [`NATIVE_SETTINGS`].
#[cfg(feature = "linked")]
pub static NATIVE_TITLES: &[paperpaw_sdk::TitleEntry] = &native_settings::TITLES;
