//! Vocabulary: the words looked up while reading, each with its sentence
//! and book, to go over later; flash cards with spaced repetition.
//!
//! The native plugin is the whole plugin (`native_plugin.rs`, declarations in
//! `declarations.rs`); see `PORTING-7.md` for what it does on interface 7 and
//! for the parts that wait for hosts (the marks in books, the dictionary
//! hand-off, mirroring for right-to-left languages).
//!
//! The words are kept in `words.txt`, newest first (`store`), the decks and
//! cards in their own files (`cards`, scheduled by `fsrs`); decks come from a
//! phone (`native_phone*`), from files in a folder of the card (`native_sd*`,
//! `sync`, `table`, `apkg`) or from the words looked up (`native_collect`).
//! Only the visible page of words, and of cards the state of those due, is
//! ever in memory.

