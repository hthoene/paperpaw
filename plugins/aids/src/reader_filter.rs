//! The rules of the settings for the reader's `reader.filter` stage (the answer), and their application to a block.
//! The entire payload is validated before any document block is changed.
use alloc::vec::Vec;
use paperpaw_sdk::Translator;
use paperpaw_sdk::document::Block;

#[rustfmt::skip]
#[allow(
    missing_docs,
    clippy::all,
    clippy::pedantic,
    reason = "generated by tools/stage-codec.py"
)]
mod stages;
use stages::reader_filter_v1 as wire;

/// Configuration cannot be represented or the incoming reply is invalid.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    /// A rule violates schema semantics.
    Invalid,
    /// The transaction or its scratch would exceed the caller budget.
    Limit,
    /// Allocation was refused before output was changed.
    NoMemory,
    /// Canonical encoder/decoder status, including aggregate size refusal.
    Wire(i32),
}

/// Encode a complete configuration. Refusal never writes a partial reply.
/// The caller must surface refusal before adopting a changed configuration.
///
/// # Errors
/// Refuses more than 32 pairs, strings over 96 bytes or a reply over 3840 bytes.
pub fn encode(
    bold: bool,
    replacements: &str,
    pictures: &str,
    caption_word: &str,
    output: &mut [u8],
) -> Result<usize, Error> {
    let mut pairs = Vec::new();
    pairs.try_reserve_exact(32).map_err(|_| Error::NoMemory)?;
    for pair in replacements.split(';') {
        let Some((from, to)) = pair.split_once('=') else {
            continue;
        };
        let (from, to) = (from.trim(), to.trim());
        if from.is_empty() {
            continue;
        }
        if pairs.len() == 32 || from.len() > 96 || to.len() > 96 {
            return Err(Error::Invalid);
        }
        pairs.push((from, to));
    }
    let policy = match pictures {
        super::pictures::CAPTION => 1,
        super::pictures::HIDE => 2,
        _ => 0,
    };
    let mut records = Vec::new();
    records
        .try_reserve_exact(pairs.len() + 1)
        .map_err(|_| Error::NoMemory)?;
    records.push(wire::Record::FilterRules(wire::FilterRules {
        signature: 0,
        bold: u32::from(bold),
        pictures: policy,
        caption_word,
    }));
    for (from, to) in &pairs {
        records.push(wire::Record::FilterPair(wire::FilterPair {
            from,
            to,
            whole_word: 1,
        }));
    }
    // Hash the canonical rules with the signature zeroed. The final encode is
    // preflighted separately, so the caller's output stays untouched on refusal.
    let mut scratch = Vec::new();
    scratch
        .try_reserve_exact(wire::MAX_REPLY)
        .map_err(|_| Error::NoMemory)?;
    scratch.resize(wire::MAX_REPLY, 0);
    let len = wire::reply_encode(&records, &mut scratch).map_err(Error::Wire)?;
    let signature = scratch[..len]
        .iter()
        .fold(0xcbf2_9ce4_8422_2325u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3)
        });
    if let Some(wire::Record::FilterRules(rules)) = records.first_mut() {
        rules.signature = signature;
    }
    wire::reply_encode(&records, output).map_err(Error::Wire)
}

/// The word that stands for a picture without a caption of its own, in the
/// language the reader asks for (a BCP 47 tag): `Bild` for German, else
/// `Picture`; the texts of `i18n/*.ini` (`aids.picture`).
#[must_use]
pub fn caption_word(language: &str) -> &'static str {
    let primary = language.split('-').next().unwrap_or("");
    if primary.eq_ignore_ascii_case("de") {
        "Bild"
    } else {
        "Picture"
    }
}

/// Answers one ask of the `reader.filter` stage: the rules of the settings
/// (`bold`, the `replacements` list, the `pictures` choice) in the reply
/// schema, the caption word in the language asked for. A book with nothing
/// but pictures keeps them whatever the choice. Nothing is written to
/// `output` when it refuses.
///
/// # Errors
/// [`Error::Invalid`] for an ask that is not one `filter.ask`; the refusals
/// of [`encode`] for rules the reply cannot hold.
pub fn answer(
    ask: &[u8],
    bold: bool,
    replacements: &str,
    pictures: &str,
    output: &mut [u8],
) -> Result<usize, Error> {
    let mut asked = wire::input_decode(ask).map_err(Error::Wire)?;
    let Some(Ok(wire::Record::FilterAsk(ask))) = asked.next() else {
        return Err(Error::Invalid);
    };
    let pictures = if ask.image_only == 0 {
        pictures
    } else {
        crate::pictures::SHOW
    };
    encode(
        bold,
        replacements,
        pictures,
        caption_word(ask.language),
        output,
    )
}

/// Apply validated rules in the existing order: bold, replacements, pictures.
/// This operates on a complete reader block, not arbitrary byte windows.
///
/// # Errors
/// Malformed or semantically invalid replies leave the block unchanged.
pub fn apply(
    bytes: &[u8],
    path: &str,
    block: &mut Block,
) -> Result<(u64, paperpaw_sdk::filters::Verdict), Error> {
    let batch = wire::reply_decode(bytes).map_err(Error::Wire)?;
    let mut rows = batch.clone();
    let Some(Ok(wire::Record::FilterRules(rules))) = rows.next() else {
        return Err(Error::Invalid);
    };
    if rules.bold > 1 || rules.pictures > 2 {
        return Err(Error::Invalid);
    }
    for row in rows {
        let Ok(wire::Record::FilterPair(pair)) = row else {
            return Err(Error::Invalid);
        };
        if pair.from.is_empty() || pair.whole_word != 1 {
            return Err(Error::Invalid);
        }
    }
    verify_signature(&batch, rules.signature)?;
    transaction::apply(&batch, rules, path, block, 64 * 1024)
}

// Re-encode through the generated codec; never depend on field byte offsets.
// Scratch is dropped before the document transaction reserves its working copy.
fn verify_signature(batch: &wire::RecordStream<'_>, signature: u64) -> Result<(), Error> {
    let mut records = Vec::new();
    records
        .try_reserve_exact(batch.len())
        .map_err(|_| Error::NoMemory)?;
    for record in batch.clone() {
        let mut record = record.map_err(Error::Wire)?;
        if let wire::Record::FilterRules(rules) = &mut record {
            rules.signature = 0;
        }
        records.push(record);
    }
    let mut scratch = Vec::new();
    scratch
        .try_reserve_exact(wire::MAX_REPLY)
        .map_err(|_| Error::NoMemory)?;
    scratch.resize(wire::MAX_REPLY, 0);
    let len = wire::reply_encode(&records, &mut scratch).map_err(Error::Wire)?;
    let computed = scratch[..len]
        .iter()
        .fold(0xcbf2_9ce4_8422_2325u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3)
        });
    if computed != signature {
        return Err(Error::Invalid);
    }
    Ok(())
}

impl From<paperpaw_sdk::document::EditError> for Error {
    fn from(error: paperpaw_sdk::document::EditError) -> Self {
        use paperpaw_sdk::document::EditError;
        match error {
            EditError::NoMemory => Self::NoMemory,
            EditError::Limit => Self::Limit,
            _ => Self::Invalid,
        }
    }
}

