/// Encode using the same localized caption label as the existing filter.
///
/// # Errors
/// Returns the same bounded configuration refusals as [`encode`].
pub fn encode_localized(
    bold: bool,
    replacements: &str,
    pictures: &str,
    i18n: &Translator,
    output: &mut [u8],
) -> Result<usize, Error> {
    encode(
        bold,
        replacements,
        pictures,
        i18n.tr("aids.picture"),
        output,
    )
}

