//! Wikipedia: a word looked up online, the short summary of its article,
//! in the language of the book (else of PaperPaw).
//!
//! The summary shows on a screen over the page like a dictionary entry: the
//! page buttons or taps scroll it, confirm or a tap outside closes it. The
//! screen fills the slot `core.lookup-online` and fetches the summary through
//! `core.net`; another plugin can take its place. What is not ported yet is
//! in `PORTING-7.md`.

