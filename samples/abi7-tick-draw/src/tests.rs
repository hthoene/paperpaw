//! Executable sample behavior through real generated callback signatures.
//! This is not a replacement loader, admission model or H1/H2/H4 fixture.
use super::*;
use std::{
    alloc::{Layout, alloc, dealloc},
    vec::Vec,
};

struct Host {
    staged: Vec<Registration>,
    reject: i32,
    no_memory: bool,
    clock_error: i32,
    micros: u64,
    allocations: usize,
    frees: usize,
    snapshot: snapshot::Snapshot,
    setting: settings::SettingValueRef<'static>,
    snapshot_error: i32,
    setting_reply: Option<i32>,
}
impl Host {
    fn new(micros: u64) -> Self {
        Self {
            staged: Vec::new(),
            reject: OK,
            no_memory: false,
            clock_error: OK,
            micros,
            allocations: 0,
            frees: 0,
            snapshot: snapshot::Snapshot::new(480, 800, 220, snapshot::PixelFormat::Mono1),
            setting: settings::SettingValueRef::Absent,
            snapshot_error: OK,
            setting_reply: None,
        }
    }
}

// SAFETY: each test passes a live, exclusively borrowed Host as its context.
unsafe fn host<'a>(ctx: *mut c_void) -> &'a mut Host {
    unsafe { &mut *ctx.cast::<Host>() }
}
unsafe extern "C" fn allocate(
    ctx: *mut c_void,
    size: usize,
    align: usize,
    out: *mut *mut c_void,
) -> i32 {
    // SAFETY: tests supply valid context/output; sample supplies valid layouts.
    let h = unsafe { host(ctx) };
    if h.no_memory {
        return ERR_NO_MEMORY;
    }
    let Ok(layout) = Layout::from_size_align(size, align) else {
        return ERR_INVALID;
    };
    // SAFETY: valid nonzero State allocation layout.
    let p = unsafe { alloc(layout) };
    if p.is_null() {
        return ERR_NO_MEMORY;
    }
    h.allocations += 1;
    // SAFETY: caller-provided output is exclusive and writable.
    unsafe {
        out.write(p.cast());
    }
    OK
}
unsafe extern "C" fn free(ctx: *mut c_void, p: *mut c_void, size: usize, align: usize) -> i32 {
    // SAFETY: this pointer/layout came from allocate and is freed exactly once.
    unsafe {
        dealloc(p.cast(), Layout::from_size_align(size, align).unwrap());
    }
    // SAFETY: live test-owned context.
    unsafe { host(ctx) }.frees += 1;
    OK
}
unsafe extern "C" fn clock(ctx: *mut c_void, out: *mut u64) -> i32 {
    // SAFETY: live test-owned context and valid output from the sample.
    let h = unsafe { host(ctx) };
    if h.clock_error != OK {
        return h.clock_error;
    }
    unsafe {
        out.write(h.micros);
    }
    OK
}
unsafe extern "C" fn register(ctx: *mut c_void, input: PpBytes) -> i32 {
    // SAFETY: sample supplies live generated bytes for synchronous copying.
    let bytes = unsafe { core::slice::from_raw_parts(input.ptr, input.len) };
    let records = match wire::registrations_decode(bytes) {
        Ok(r) => r,
        Err(e) => return e,
    };
    // SAFETY: live test-owned context.
    let h = unsafe { host(ctx) };
    if h.reject != OK {
        return h.reject;
    }
    h.staged.extend(records.iter());
    OK
}
unsafe extern "C" fn copy_snapshot(ctx: *mut c_void, output: PpBuffer) -> i32 {
    // SAFETY: test context and exclusive output follow the host callback contract.
    let h = unsafe { host(ctx) };
    if h.snapshot_error != OK {
        return h.snapshot_error;
    }
    let out = unsafe {
        core::slice::from_raw_parts_mut(output.ptr.cast::<core::mem::MaybeUninit<u8>>(), output.cap)
    };
    match snapshot::snapshot_encode(&h.snapshot, out) {
        Ok(_) => OK,
        Err(e) => e,
    }
}
unsafe extern "C" fn read_setting(ctx: *mut c_void, key: PpBytes, output: PpBuffer) -> i32 {
    // SAFETY: generated sample key is live and initialized for this synchronous call.
    let key = unsafe { core::slice::from_raw_parts(key.ptr, key.len) };
    assert_eq!(key, observations::SETTING_KEY);
    // SAFETY: test context and output remain valid and disjoint from key/storage.
    let h = unsafe { host(ctx) };
    if let Some(error) = h.setting_reply.filter(|v| *v < 0) {
        return error;
    }
    let out = unsafe {
        core::slice::from_raw_parts_mut(output.ptr.cast::<core::mem::MaybeUninit<u8>>(), output.cap)
    };
    match settings::settings_encode(h.setting, out) {
        Ok(required) => h.setting_reply.unwrap_or(required as i32),
        Err(error) => error,
    }
}
fn table() -> PpHost {
    let mut table = paperpaw_native::host_glue::host_table();
    table.heap_alloc = allocate;
    table.heap_dealloc = free;
    table.clock_micros = clock;
    table.registrations_submit = register;
    table.env_snapshot = copy_snapshot;
    table.settings_read = read_setting;
    table
}
fn create(table: &PpHost, ctx: &mut Host) -> *const PpPlugin {
    let mut plugin = ptr::null();
    // SAFETY: table and context outlive all callbacks/destruction in each test.
    assert_eq!(
        unsafe { make(table, ptr::from_mut(ctx).cast(), &mut plugin) },
        OK
    );
    assert!(!plugin.is_null());
    plugin
}
fn tick(plugin: *const PpPlugin, token: u32, now: u64) -> i32 {
    let mut bytes = [0; 64];
    let len = wire::tick_encode(now, &mut bytes).unwrap();
    // SAFETY: created instance lives through callback; generated bytes are borrowed.
    unsafe {
        ((*plugin).dispatch_event.unwrap())(
            (*plugin).state,
            token,
            PpBytes {
                ptr: bytes.as_ptr(),
                len,
            },
        )
    }
}
fn destroy_plugin(plugin: *const PpPlugin) {
    // SAFETY: each test calls this once, after its synchronous callbacks finish.
    unsafe {
        ((*plugin).drop.unwrap())((*plugin).state);
    }
}

#[test]
fn instance_registers_then_remembers_tick_and_draw_without_global_host_state() {
    let table = table();
    let (mut a, mut b) = (Host::new(41_000), Host::new(92_000));
    let (pa, pb) = (create(&table, &mut a), create(&table, &mut b));
    assert_eq!(
        a.staged,
        [
            Registration::Event {
                event_tag: EVENT_TICK_TAG,
                token: EVENT_TOKEN
            },
            Registration::Draw { token: DRAW_TOKEN }
        ]
    );
    assert_eq!(tick(pa, EVENT_TOKEN, 41), OK);
    assert_eq!(tick(pb, EVENT_TOKEN, 92), OK);
    // SAFETY: distinct created live instances, synchronously invoked then inspected.
    unsafe {
        assert_eq!(((*pa).draw.unwrap())((*pa).state, DRAW_TOKEN), OK);
        assert_eq!(((*pb).draw.unwrap())((*pb).state, DRAW_TOKEN), OK);
        for (p, now) in [(pa, 41), (pb, 92)] {
            let s = &*(*p).state.cast::<State>();
            assert_eq!(s.last_tick_ms, Some(now));
            assert_eq!((s.ticks, s.draws, s.draw_clock_us), (1, 1, now * 1000));
        }
    }
    destroy_plugin(pa);
    destroy_plugin(pb);
    assert_eq!(
        (a.allocations, a.frees, b.allocations, b.frees),
        (1, 1, 1, 1)
    );
}

#[test]
fn malformed_input_and_wrong_tokens_leave_local_state_unchanged() {
    let table = table();
    let mut ctx = Host::new(1);
    let p = create(&table, &mut ctx);
    assert_eq!(tick(p, DRAW_TOKEN, 1), ERR_INVALID);
    let mut bytes = [0; 64];
    let n = wire::tick_encode(7, &mut bytes).unwrap();
    // SAFETY: live instance and valid borrowed buffer, deliberately truncated length.
    unsafe {
        assert_eq!(
            ((*p).dispatch_event.unwrap())(
                (*p).state,
                EVENT_TOKEN,
                PpBytes {
                    ptr: bytes.as_ptr(),
                    len: n - 1
                }
            ),
            ERR_INVALID
        );
        assert_eq!(((*p).draw.unwrap())((*p).state, EVENT_TOKEN), ERR_INVALID);
        assert_eq!(((*p).state.cast::<State>()).as_ref().unwrap().ticks, 0);
        assert_eq!(((*p).state.cast::<State>()).as_ref().unwrap().draws, 0);
    }
    destroy_plugin(p);
}

#[test]
fn host_refusal_and_allocation_failure_publish_no_instance() {
    let table = table();
    for (reject, no_memory, expected) in [
        (ERR_NO_SPACE, false, ERR_NO_SPACE),
        (OK, true, ERR_NO_MEMORY),
    ] {
        let mut ctx = Host::new(1);
        ctx.reject = reject;
        ctx.no_memory = no_memory;
        let mut out = ptr::null();
        // SAFETY: table/context/output are valid; host intentionally refuses a call.
        assert_eq!(
            unsafe { make(&table, ptr::from_mut(&mut ctx).cast(), &mut out) },
            expected
        );
        assert!(out.is_null());
        assert_eq!((ctx.allocations, ctx.frees), (0, 0));
        // Staging rollback is host-owned and qualified separately by PR #153.
    }
}

#[test]
fn clock_error_does_not_commit_a_draw() {
    let table = table();
    let mut ctx = Host::new(1);
    let p = create(&table, &mut ctx);
    ctx.clock_error = ERR_IO;
    // SAFETY: live instance/context; host intentionally refuses the clock query.
    unsafe {
        assert_eq!(((*p).draw.unwrap())((*p).state, DRAW_TOKEN), ERR_IO);
        assert_eq!((*(*p).state.cast::<State>()).draws, 0);
    }
    destroy_plugin(p);
}

